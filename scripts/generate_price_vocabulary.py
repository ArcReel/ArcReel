#!/usr/bin/env python3
"""Generate price-editor vocabulary as a frontend TS file.

Meters and selection dimensions are closed sets defined in ``arcreel_catalog_core.vocabulary``.
Generate each meter’s media types, kind, quantity per price, and each dimension’s media types from
those sets instead of maintaining a second frontend definition. Rerun after set changes;
``tests/unit/scripts/test_generate_price_vocabulary.py`` verifies the output is current.

Usage:
    uv run python scripts/generate_price_vocabulary.py
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

from arcreel_catalog_core import (
    CJK_DOUBLE_METER,
    CURRENCIES,
    DIMENSION_MEDIA_TYPES,
    DIMENSIONS,
    MEDIA_TYPES,
    METERS,
    SERVICE_TIERS,
)

OUTPUT_PATH = (
    Path(__file__).resolve().parents[1]
    / "frontend/src/components/pages/settings/price-editor/priceVocabulary.generated.ts"
)


def _list(values: Iterable[str]) -> str:
    return json.dumps(list(values), ensure_ascii=False)


def render() -> str:
    lines = [
        "// Generated by scripts/generate_price_vocabulary.py from arcreel_catalog_core.vocabulary. Do not edit manually.",
        "// Code defines the closed sets of meters and dimensions; rerun this script when those sets change.",
        "",
        f"export const PRICE_CURRENCIES = {_list(CURRENCIES)} as const;",
        f"export const PRICE_SERVICE_TIERS = {_list(SERVICE_TIERS)} as const;",
        f"export const CJK_DOUBLE_METER = {json.dumps(CJK_DOUBLE_METER)};",
        "",
        "/** Meters: entries whose `kind` is token partition the same total token count; `per` is the quantity covered by one unit price. */",
        "export const METERS = {",
    ]
    for key, spec in METERS.items():
        media = _list(m for m in MEDIA_TYPES if m in spec.media_types)
        lines.append(
            f'  {key}: {{ kind: "{spec.kind}", per: {spec.quantity_per_price}, mediaTypes: {media} }},',
        )
    lines += ["} as const;", "", "/** Dimensions: `kind` is the value shape. */", "export const DIMENSIONS = {"]
    for key, kind in DIMENSIONS.items():
        media = _list(m for m in MEDIA_TYPES if m in DIMENSION_MEDIA_TYPES[key])
        lines.append(f'  {key}: {{ kind: "{kind}", mediaTypes: {media} }},')
    lines += ["} as const;", ""]
    return "\n".join(lines)


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
