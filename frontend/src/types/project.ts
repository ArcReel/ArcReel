/** Reason a duration was excluded by combined constraints. Durations absent from the model's full set are not represented by these reasons; identify them by absence from supported_durations. */
export type DurationExclusionReason = "resolution" | "reference";

/**
 * Duration narrowing results and reasons for a constraint context, calculated by the server from that bucket's video request facts
 * (`lib/generation/video_request_facts.py`); the frontend only looks them up and does not own the narrowing rules.
 */
export interface DurationConstraints {
  /** Effective resolution used for evaluation; null means no narrowing by resolution. */
  resolution: string | null;
  uses_reference_images: boolean;
  /** Narrowed results in ascending order. */
  allowed: number[];
  /**
   * Selectable script planning tiers in ascending order: usually equal to `allowed`; when duration is fixed by the endpoint, these are tiers borrowed for planning. Content confirmation uses them
   * to detect tier overruns, matching server confirmation conversion. Returned only by the project endpoint.
   */
  planning?: number[];
  /** Durations excluded from the full set (keys are seconds as strings) → reasons. */
  excluded: Record<string, DurationExclusionReason>;
}

