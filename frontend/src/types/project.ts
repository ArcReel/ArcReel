export interface ProjectData {
  title: string;
  content_mode: "narration" | "drama" | "ad";
  style: string;
  style_template_id?: string | null;
  style_image?: string;
  style_description?: string;
  overview?: ProjectOverview;
  aspect_ratio?: string | AspectRatio;  // A string for new projects; legacy projects may use a dict
  default_duration?: number | null;     // Default video duration for new storyboards (seconds); null lets the AI decide from content; absent on ad projects
  episode_target_duration?: number | null;  // Soft preference for target episode final-cut duration (seconds); null means no target; absent on ad projects
  /** Ad only: target total duration (seconds). */
  target_duration?: number;
  /** Ad only: short creative brief (may be empty). */
  brief?: string;
  schema_version?: number;
  /** Whole-source file list in the order arranged by the creator. */
  whole_source_files?: { source_file: string; source_kind?: "novel" | "screenplay" }[];
  episodes: EpisodeMeta[];
  characters: Record<string, Character>;
  scenes?: Record<string, Scene>;
  props?: Record<string, Prop>;
  /** Product assets (used by ad/short-film projects; v1 assumes a single product, with a mapping-shaped field). */
  products?: Record<string, Product>;
  /** Project summary projection, injected at read time */
  status?: ProjectStatus;
  video_backend?: string | null;
  /** Project-level override for video task type buckets (docs/adr/0054); null falls back to video_backend and the global layer */
  video_provider_i2v?: string | null;
  video_provider_r2v?: string | null;
  image_backend?: string | null;
  /** Project default image model; unset image task type buckets fall back to it, then to the global layer */
  default_image_backend?: string | null;
  image_provider_t2i?: string | null;
  image_provider_i2i?: string | null;
  /** Generation mode, locked at creation and immutable afterward. */
  generation_mode?: GenerationRoute;
  /** Grid storyboard assembly switch; meaningful only for storyboard image-to-video and changeable at any time. */
  grid_storyboard?: boolean;
  video_generate_audio?: boolean | null;
  /** Character voice binding: prompt (default, a soft constraint from voice_style) / reference_audio (attaches character reference audio). */
  character_voice_binding?: CharacterVoiceBinding;
  /** Narration delivery (docs/adr/0089): TTS or post-production dubbing; defaults to post-production dubbing */
  narration_delivery?: NarrationDelivery;
  /** TTS snapshot: provider/model, voice, and speed. Prefilled from global defaults at creation, then no longer inherits them;
   *  retained after switching to post-production dubbing. Unset speed means no speed is sent to the provider */
  audio_backend?: string | null;
  narration_voice?: string | null;
  narration_speed?: number | null;
  /** Source language code (zh / en / vi / ru), written by content analysis; read-only in the UI and used for spoken-rate unit labels */
  source_language?: string | null;
  /** Project-level spoken-rate estimate override (reading units / second); unset uses the default rate for the project language */
  speech_rate_units_per_second?: number | null;
  text_backend_simple?: string | null;
  text_backend_complex?: string | null;
  default_text_backend?: string | null;
  model_settings?: Record<string, ModelSettingEntry>;
  /** Legacy field: keyed by model_id only (before composite key refactor). Read-only at UI layer. */
  video_model_settings?: Record<string, { resolution?: string | null }>;
  metadata?: {
    created_at: string;
    updated_at: string;
  };
}

