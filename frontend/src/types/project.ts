export interface ProjectOverview {
  synopsis: string;
  genre: string;
  theme: string;
  world_setting: string;
  generated_at?: string;
}

/**
 * A character derivative: another persistent appearance beyond the base look (costume changes, transformations, disguises, etc.). It shares the base's name, voice,
 * and identity, holding only a description of changes relative to the base and an asset sheet, without an original image. Its sheet is generated by editing the base's sheet or replaced by an uploaded finished image.
 */
export interface CharacterDerivative {
  /** Appearance changes relative to the base, phrased as image editing instructions. */
  description: string;
  /** Relative path of the derivative asset sheet; empty before generation. */
  character_sheet?: string;
  /** Whether the script contains `@[角色/衍生]` or `角色/衍生`. Computed at read time, not persisted, and returned with the entry when reading the project. */
  referenced?: boolean;
}

/** Derivative read view: registered fields plus whether the sheet is stale relative to the base's current state. */
export interface CharacterDerivativeStatus extends CharacterDerivative {
  /** True when the registered derivative sheet no longer matches the canonical state; false if never generated. */
  stale: boolean;
  /** Artifact manifest status; missing when the registered file is unreadable. */
  artifact_status?: "current" | "stale" | "missing" | "blocked";
}

export interface Character {
  description: string;
  character_sheet?: string;
  voice_style?: string;
  reference_image?: string;
  reference_audio?: string;
  /** Set/update time (ISO8601) of the effective reference_audio version, stamped automatically by the backend on write. */
  voice_updated_at?: string;
  /** Acknowledged voice version (ISO8601, the original voice_updated_at value when dismissed);
   *  a later voice_updated_at is considered a new version. */
  voice_notice_dismissed_at?: string;
  /** Derivative table: derivative name → entry. Names are unique only within this character and are written as `@[角色/衍生]` in scripts. */
  derivatives?: Record<string, CharacterDerivative>;
  /** Aliases: used only as identification references during AI planning, not for references. */
  aliases?: string[];
}

export interface Scene {
  description: string;
  scene_sheet?: string;
  /** Aliases: used only as identification references during AI planning, not for references. */
  aliases?: string[];
}

export interface Prop {
  description: string;
  prop_sheet?: string;
  /** Aliases: used only as identification references during AI planning, not for references. */
  aliases?: string[];
}

export interface Product {
  description: string;
  /** Standard product asset sheet (optional, written back after generation/upload). */
  product_sheet?: string;
  /** Free text describing brand elements. */
  brand?: string;
  /** Paths of original product images uploaded by the user (fidelity acceptance anchors, a system-level field). */
  reference_images?: string[];
  /** Selling points (drafted by the Agent and editable by the user). */
  selling_points?: string[];
}

export interface AspectRatio {
  characters?: string;
  scenes?: string;
  props?: string;
  storyboard?: string;
  video?: string;
}

export interface EpisodesSummary {
  total: number;
  scripted: number;
  in_production: number;
  completed: number;
}

/** One artifact group: available = current plus stale, stale counted separately */
export interface ArtifactCount {
  total: number;
  available: number;
  stale: number;
}

/** Project summary projection, injected at read time by WorkflowStateService */
export interface ProjectStatus {
  /** Schema migration (artifact backfill included) failed; generation is closed until repaired */
  needs_repair: boolean;
  /** The migration failure message exactly as raised, or null when not blocked */
  repair_reason: string | null;
  /** Asset sheet counts keyed by asset type (character / scene / prop / product) */
  assets: Record<string, ArtifactCount>;
  episodes_summary: EpisodesSummary;
  /** The whole source still has text not yet planned into episodes; recorded by ledger commands, not read from source */
  source_remaining: boolean;
}

/**
 * Structure for referring to entries outside the episode page (backend `with_episode_item_refs`): entry IDs are not shown to creators;
 * the UI formats them as "Title · 5", using the broadcast position when the title is empty.
 */
export interface EpisodeItemRef {
  episode_title: string;
  episode_position: number;
  /** Episode-local ID, such as S01 / U02; used only for entries like grids that are not referred to by position. */
  item_id: string;
  /** Current position of the storyboard or video unit within this episode, starting at 1; null when the entry is no longer in the script. */
  item_position: number | null;
  /** The first dozen or so characters of the body; an empty string when the entry is no longer in the script. */
  item_excerpt: string;
  /** Project-relative thumbnail path. */
  item_thumbnail: string | null;
}

export interface EpisodeMeta {
  episode: number;
  title: string;
  script_file: string;
  /** Written by episode_planner at split time: ending hook / suspense */
  hook?: string;
  /** Source range of the split episode within the whole source (code point offsets in normalized text); `end` belongs to `end_file`, which defaults to `source_file`. */
  source_range?: { source_file?: string; start?: number; end?: number; end_file?: string };
  /**
   * Origin of this episode's source: split from the whole source, its own source (uploaded per episode or entered on its page), or none.
   * Defaults to inference from the presence of source_range.
   */
  source_origin?: "whole_source" | "own" | "none";
  /** Source kind of an episode with its own source, recorded only for drama projects. */
  source_kind?: "novel" | "screenplay";
  /**
   * Episode planning state. Only stale is meaningful to creators: this episode's source has been replanned or edited/deleted,
   * which is separate from artifact staleness (stale storyboards / videos).
   */
  ledger_status?: "planned" | "consumed" | "stale";
  /** Written by episode_planner at split time (drama only) */
  outline?: { story_beats?: string[]; next_episode_teaser?: string };
  /** Additional instructions from the last prompt authoring run, prefilled when opening "Author prompts" */
  prompt_authoring_instructions?: string;
  /** Additional instructions from the last AI script planning run, prefilled on regeneration */
  script_plan_instructions?: string;
  /**
   * Per-episode fields below come from the project summary at read time, on the artifact
   * manifest's terms — the same numbers the studio reads, never persisted to project.json.
   * Optional because the fallback meta some canvases build has no summary behind it.
   *
   * item_count is the episode's content size: storyboard count for storyboard image-to-video, or video unit count for reference video.
   * Counting is determined by the project's generation_mode and is consistent across all three content modes.
   */
  item_count?: number;
  /** Script progress derived from the script_plan and final-script artifact states */
  script_status?: "none" | "segmented" | "generated";
  status?: "draft" | "scripted" | "in_production" | "completed" | "missing";
  duration_seconds?: number;
  storyboards?: ArtifactCount;
  videos?: ArtifactCount;
}

/** Character voice binding method; corresponds exactly to backend `lib.speech.character_voice.CharacterVoiceBinding`, and value additions/removals must stay synchronized. */
export type CharacterVoiceBinding = "prompt" | "reference_audio";

/** Default when undeclared: a soft prompt constraint. Reference audio is an optional enhancement requiring explicit user selection. */
export const DEFAULT_CHARACTER_VOICE_BINDING: CharacterVoiceBinding = "prompt";

