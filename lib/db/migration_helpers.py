"""Schema helpers shared by Alembic migrations.

Keep these in lib rather than alembic/: the installed Alembic package owns the import
name ``alembic``, preventing migration scripts from importing sibling modules beside
the versions directory. The project root is already on sys.path during migrations
(``prepend_sys_path = .`` in alembic.ini).
"""

from __future__ import annotations

from collections.abc import Generator
from contextlib import contextmanager

import sqlalchemy as sa
from sqlalchemy.engine import Connection

from alembic import op


def _index_ddl(bind: Connection, table_name: str) -> dict[str, str]:
    """Read raw index DDL for the table from sqlite_master.

    ``sql IS NOT NULL`` excludes ``sqlite_autoindex_*`` indexes implicitly generated by
    UNIQUE constraints: they belong to table definitions and have no standalone DDL to replay.
    """
    rows = bind.execute(
        sa.text("SELECT name, sql FROM sqlite_master WHERE type = 'index' AND tbl_name = :table AND sql IS NOT NULL"),
        {"table": table_name},
    ).fetchall()
    return {row[0]: row[1] for row in rows}


@contextmanager
def preserve_sqlite_indexes(table_name: str) -> Generator[None]:
    """Preserve indexes that cannot be reflected during SQLite table rebuilds.

    Adding/removing columns with ``batch_alter_table`` rebuilds SQLite tables. SQLAlchemy
    cannot reflect expression-based indexes, emitting only
    ``SAWarning: Skipped unsupported reflection of expression-based index``. These indexes
    silently disappear on rebuild; this lost ``idx_tasks_dedupe_active`` on ``tasks``,
    disabling deduplication and permitting two concurrent active tasks for one resource.
    Capture raw DDL from ``sqlite_master`` on entry and replay missing indexes unchanged on
    exit, avoiding duplicated index definitions that drift across later migrations.
    PostgreSQL uses native ALTER without rebuilding, so this is a no-op there.

    Replay detects indexes present before entry and missing on exit, without distinguishing
    silent loss from intentional deletion. Drop indexes intentionally outside this context
    (``DROP INDEX`` is native in both dialects and does not trigger rebuilds).
    """
    bind = op.get_bind()
    if bind.dialect.name != "sqlite":
        yield
        return

    captured = _index_ddl(bind, table_name)
    yield
    surviving = _index_ddl(bind, table_name)
    for name, ddl in captured.items():
        if name not in surviving:
            op.execute(ddl)
