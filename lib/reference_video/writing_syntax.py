"""参考生视频「书写层」语法规范——唯一真相源。

LLM 在 step1 / step2 产出的 unit 正文与人在编辑器里写的是同一种格式，因此语法规范
只能有一份措辞：本模块的 :data:`WRITING_SYNTAX_SPEC` 由两级 prompt builder
（``build_reference_units_split_prompt`` / ``build_reference_video_prompt``）共同注入，
agent 侧文档只留概览并指向工具，前端语法提示另走 i18n 三语，均不复制全文。

放在 ``lib/reference_video/`` 与 :mod:`lib.reference_video.shot_parser` 同域：规范措辞与
执行它的解析器同进同退，改语法时两者在同一目录里对照修改。
"""

from __future__ import annotations

#: 单 unit 允许的镜头行数上限（``镜头N：`` 行）。unit 是一次生成调用，镜头只是同一段
#: clip 内的画面切换；与 ``ReferenceVideoUnit.shots`` 的 ``max_length`` 同一口径。
MAX_SHOTS_PER_UNIT = 4

WRITING_SYNTAX_SPEC = f"""每个 unit 的正文是一段**扁平文本**，按行书写，只有三种行：

1. **镜头行**——以 `镜头N：` 开头（N 从 1 起递增，中英冒号均可），其后是该镜头的画面描述。
   一个 unit 最多 {MAX_SHOTS_PER_UNIT} 个镜头行；镜头行不带秒数，时长是 unit 级字段。
2. **台词行**——`@[角色名]：{{台词内容}}`，独立成行、整行只有这个结构。
   花括号 `{{}}` 里是逐字台词；角色名必须是已登记的角色资产名。
3. **画外音行**——`{{台词内容}}`，独立成行、整行只被一对花括号包裹，表示画外音（不指定说话人）。

资产引用：角色 / 场景 / 道具一律写成 `@[名称]`，名称逐字取自候选表，不要发明表外的名称。

硬性约束（违反即整份产出被拒）：

- 花括号只用于台词行与画外音行，且必须整行包裹、成对闭合、不嵌套；
  **镜头行的画面描述里不得出现 `{{` 或 `}}`**——台词写进画面描述不会被识别为台词。
- 台词单独成行，不与画面描述混写在同一行；台词行不承担画面描述职能。
- 每个 `@[名称]` 都必须是候选表中已登记的资产名，台词行的角色名同样如此。
- 画面描述不写外貌 / 服装 / 场景陈设 / 色调光影——静态外观由参考图承担；
  泛指群演（老人甲 / 村民若干）直接写进描述即可，不用 `@` 引用。

示例（一个 unit 的正文）：

```
镜头1：@[李明] 推开 @[酒馆] 的木门，侧身跨过门槛，目光扫过厅内。
@[李明]：{{这地方比我想的还热闹。}}
镜头2：@[李明] 走向柜台，把 @[长剑] 横放在台面上，指节在剑鞘上叩了两下。
{{他知道，今晚不会太平。}}
```"""


__all__ = ["MAX_SHOTS_PER_UNIT", "WRITING_SYNTAX_SPEC"]
